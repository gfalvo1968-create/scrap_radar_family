const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'..','board_case_tray.js'),'utf8');
const begin=source.indexOf('function caseUploadError(');
const end=source.indexOf('async function run(){',begin);
assert.ok(begin>=0&&end>begin,'caseUploadError must be present');
const sandbox={};
vm.runInNewContext(source.slice(begin,end),sandbox);
const describe=(status,body)=>sandbox.caseUploadError(status,body);
assert.match(describe(429,{status:'limit_reached',message:'Your free analysis for today has already been used.'}),/already been used/);
assert.match(describe(429,null),/tomorrow/);
assert.match(describe(413,{detail:'Image exceeds the 10 MB limit'}),/10 MB/);
assert.match(describe(415,{detail:'Unsupported image'}),/HEIC/);
assert.match(describe(503,{status:'temporarily_unavailable'}),/temporarily unavailable/);
assert.match(describe(422,{detail:'Invalid photos'}),/Invalid photos/);
assert.match(describe(500,{detail:'private backend traceback'}),/server problem/);
assert.doesNotMatch(describe(500,{detail:'private backend traceback'}),/traceback/);
assert.match(describe(418,null),/HTTP 418/);
console.log('Case HTTP error feedback tests passed');